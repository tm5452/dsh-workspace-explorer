#!/usr/bin/env node
/**
 * make-card-icon.mjs — turn the guide card's artwork into a module the bundle can carry.
 *
 * The plugin ships as one classic script and cannot serve files at runtime, so the drawing has
 * to be inlined. It is inlined as SVG *markup*, not as an image data URI: the card is drawn 26px
 * tall, and a vector is rasterised at that size (a few KiB of pixels) instead of a bitmap being
 * decoded at its own resolution (~167 KiB for the old 233x183 PNG) and then scaled back down.
 *
 * The source has to be real vector art. A Figma export that wraps a PNG in <image> is refused
 * below: it costs the same bytes as more, and gains nothing in memory.
 *
 * Re-run with `node scripts/make-card-icon.mjs` after replacing either icon in assets/.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const pkgRoot = path.resolve(here, '..');
async function generateIcon(assetName, exportName, moduleName = assetName) {
  const source = path.join(pkgRoot, 'assets', assetName + '.svg');
  const target = path.join(pkgRoot, 'src', 'ui', moduleName + '.js');
  const idPrefix = 'dwe-' + moduleName + '-';

  const text = await readFile(source, 'utf8');

  const root = /<svg\b[^>]*>/i.exec(text);
  if (!root) throw new Error(`[icon] ${source} 里没有 <svg> 根元素`);

  if (/<image\b/i.test(text)) {
    throw new Error(
      '[icon] ' + assetName + '.svg 里嵌了 <image>：这是把位图包进 SVG，体积不会小，内存也和 PNG 一样，'
      + '要先导出成真的矢量路径再放进来',
    );
  }

  const viewBoxAttribute = /\sviewBox\s*=\s*["']([^"']+)["']/.exec(root[0]);
  if (!viewBoxAttribute) throw new Error('[icon] <svg> 上没有 viewBox，缩放无从下手');

  const viewBox = viewBoxAttribute[1].trim().replace(/[\s,]+/g, ' ');
  const [, , boxWidth, boxHeight] = viewBox.split(' ').map(Number);
  if (!(boxWidth > 0 && boxHeight > 0)) throw new Error(`[icon] viewBox 读不懂: ${viewBox}`);

  const close = text.lastIndexOf('</svg>');
  if (close < 0) throw new Error('[icon] 文件没有 </svg>');
  let markup = text.slice(root.index + root[0].length, close).trim();

  // Gradient and clip ids are document-global. A Figma export defaults to names like
  // paint0_linear_85_25, so a second copy of this artwork (or another export in the same page)
  // would silently repaint ours. Namespace every id once, here, where it is cheap.
  const ids = new Set([...markup.matchAll(/\sid="([^"]+)"/g)].map(match => match[1]));
  for (const id of ids) {
    markup = markup
      .replaceAll(`id="${id}"`, `id="${idPrefix}${id}"`)
      .replaceAll(`url(#${id})`, `url(#${idPrefix}${id})`)
      .replaceAll(`href="#${id}"`, `href="#${idPrefix}${id}"`);
  }

  const module = `/* Generated by scripts/make-card-icon.mjs from assets/${assetName}.svg — do not edit. */
export const ${exportName}ViewBox = ${JSON.stringify(viewBox)};
export const ${exportName}Ratio = ${boxWidth} / ${boxHeight};
export const ${exportName}Markup = ${JSON.stringify(markup)};
`;

  await writeFile(target, module, 'utf8');
  console.log(
    `[icon] ${viewBox} → src/ui/${moduleName}.js `
    + `(${(Buffer.byteLength(markup) / 1024).toFixed(2)} KiB markup, ${ids.size} ids namespaced)`,
  );
}

await generateIcon('card-icon', 'cardIcon');
await generateIcon('my-pc', 'myPcIcon', 'my-pc-icon');
